CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    description VARCHAR(2000),
    url VARCHAR(1000) NOT NULL,
    image_url VARCHAR(1000),
    source VARCHAR(150),
    published_at TIMESTAMP,
    CONSTRAINT uq_news_url UNIQUE (url)
);

CREATE TABLE preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category VARCHAR(50) NOT NULL,
    CONSTRAINT fk_preferences_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_preferences_user_category UNIQUE (user_id, category)
);

CREATE TABLE read_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    news_id BIGINT NOT NULL,
    read_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_read_history_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_read_history_news FOREIGN KEY (news_id) REFERENCES news (id)
);

CREATE INDEX idx_read_history_user_id ON read_history (user_id);

CREATE TABLE favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    news_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_favorites_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_favorites_news FOREIGN KEY (news_id) REFERENCES news (id),
    CONSTRAINT uq_favorites_user_news UNIQUE (user_id, news_id)
);